export const translations = { en, sw } as const;

export type TranslationKey = keyof typeof en;

export function t(
  locale: Locale,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  let text: string =
    translations[locale][key] || translations.en[key] || String(key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return text;
}

export function roleLabel(locale: Locale, role: string): string {
  const key = `role${role}` as TranslationKey;
  if (key in translations.en) return t(locale, key);
  return role.replace(/_/g, " ");
}
